package com.example.ui.screens

import android.widget.Toast
import androidx.compose.foundation.BorderStroke
import androidx.compose.foundation.background
import androidx.compose.foundation.border
import androidx.compose.foundation.layout.*
import androidx.compose.foundation.lazy.LazyColumn
import androidx.compose.foundation.lazy.items
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.shape.CircleShape
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.foundation.verticalScroll
import androidx.compose.material.icons.Icons
import androidx.compose.material.icons.automirrored.outlined.VolumeUp
import androidx.compose.material.icons.filled.*
import androidx.compose.material.icons.outlined.*
import androidx.compose.material3.*
import androidx.compose.runtime.*
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.draw.clip
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import com.example.NovaViewModel
import com.example.ui.theme.*

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun CallAssistantScreen(
    viewModel: NovaViewModel,
    onBack: () -> Unit,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current
    val voiceScripts by viewModel.voiceScripts.collectAsState()
    val selectedVoiceName by viewModel.selectedVoiceName.collectAsState()

    var phoneNumberInput by remember { mutableStateOf("") }
    var scriptTitleInput by remember { mutableStateOf("") }
    var scriptContentInput by remember { mutableStateOf("") }

    // Autonomous call states
    var autoRecipientInput by remember { mutableStateOf("") }
    var autoMessageInput by remember { mutableStateOf("আমি সন্ধ্যা ৬টায় পৌঁছাব।") }
    var autoGeneratedScript by remember { mutableStateOf("") }

    var selectedTab by remember { mutableIntStateOf(0) }

    Scaffold(
        modifier = modifier.fillMaxSize(),
        containerColor = NovaBackgroundIce,
        topBar = {
            TopAppBar(
                title = {
                    Text(
                        "কল অ্যাসিস্ট্যান্ট & এআই ভয়েস",
                        fontWeight = FontWeight.Bold,
                        fontSize = 18.sp,
                        color = NovaTextPrimary
                    )
                },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.Default.ArrowBack, contentDescription = "Back", tint = NovaTextPrimary)
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = Color.White)
            )
        }
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
        ) {
            // Tabs
            TabRow(
                selectedTabIndex = selectedTab,
                containerColor = Color.White,
                contentColor = NovaElectricBlue
            ) {
                Tab(
                    selected = selectedTab == 0,
                    onClick = { selectedTab = 0 },
                    text = { Text("ফোন ডায়ালার", fontWeight = FontWeight.SemiBold, fontSize = 13.sp) }
                )
                Tab(
                    selected = selectedTab == 1,
                    onClick = { selectedTab = 1 },
                    text = { Text("এআই কল বার্তা", fontWeight = FontWeight.SemiBold, fontSize = 13.sp) }
                )
                Tab(
                    selected = selectedTab == 2,
                    onClick = { selectedTab = 2 },
                    text = { Text("ভয়েস স্ক্রিপ্ট", fontWeight = FontWeight.SemiBold, fontSize = 13.sp) }
                )
            }

            when (selectedTab) {
                0 -> {
                    // Smart Dialer Tab
                    Column(
                        modifier = Modifier
                            .fillMaxSize()
                            .verticalScroll(rememberScrollState())
                            .padding(16.dp),
                        verticalArrangement = Arrangement.spacedBy(16.dp)
                    ) {
                        Surface(
                            shape = RoundedCornerShape(16.dp),
                            color = Color.White,
                            shadowElevation = 2.dp
                        ) {
                            Column(modifier = Modifier.padding(16.dp)) {
                                Row(verticalAlignment = Alignment.CenterVertically) {
                                    Box(
                                        modifier = Modifier
                                            .size(40.dp)
                                            .clip(CircleShape)
                                            .background(NovaSoftSky),
                                        contentAlignment = Alignment.Center
                                    ) {
                                        Icon(Icons.Default.Phone, contentDescription = null, tint = NovaElectricBlue)
                                    }
                                    Spacer(modifier = Modifier.width(12.dp))
                                    Column {
                                        Text("স্মার্ট কল ডায়াল", fontWeight = FontWeight.Bold, fontSize = 16.sp)
                                        Text("নম্বর বা কন্টাক্ট খুঁজে সরাসরি ডায়ালার চালু করুন", fontSize = 12.sp, color = NovaTextSecondary)
                                    }
                                }

                                Spacer(modifier = Modifier.height(16.dp))

                                OutlinedTextField(
                                    value = phoneNumberInput,
                                    onValueChange = { phoneNumberInput = it },
                                    label = { Text("ফোন নম্বর বা নাম") },
                                    placeholder = { Text("যেমন: 01700000000 বা রহিম") },
                                    singleLine = true,
                                    modifier = Modifier.fillMaxWidth(),
                                    shape = RoundedCornerShape(12.dp)
                                )

                                Spacer(modifier = Modifier.height(14.dp))

                                Row(
                                    modifier = Modifier.fillMaxWidth(),
                                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                                ) {
                                    Button(
                                        onClick = { viewModel.actionEngine.openDialer(phoneNumberInput) },
                                        shape = RoundedCornerShape(12.dp),
                                        colors = ButtonDefaults.buttonColors(containerColor = NovaElectricBlue),
                                        modifier = Modifier.weight(1f).height(48.dp)
                                    ) {
                                        Icon(Icons.Default.Call, contentDescription = null)
                                        Spacer(modifier = Modifier.width(6.dp))
                                        Text("ডায়াল করুন", fontWeight = FontWeight.SemiBold)
                                    }

                                    OutlinedButton(
                                        onClick = { viewModel.actionEngine.openContacts() },
                                        shape = RoundedCornerShape(12.dp),
                                        modifier = Modifier.weight(1f).height(48.dp)
                                    ) {
                                        Icon(Icons.Outlined.Contacts, contentDescription = null, tint = NovaTextPrimary)
                                        Spacer(modifier = Modifier.width(6.dp))
                                        Text("কন্টাক্টস", color = NovaTextPrimary)
                                    }
                                }
                            }
                        }

                        // Technical limitation notice
                        Surface(
                            shape = RoundedCornerShape(16.dp),
                            color = NovaSoftSky,
                            border = BorderStroke(1.dp, NovaElectricBlue.copy(alpha = 0.3f))
                        ) {
                            Column(modifier = Modifier.padding(14.dp)) {
                                Text(
                                    text = "অ্যান্ড্রয়েড সেলুলার অডিও নীতি:",
                                    fontWeight = FontWeight.Bold,
                                    fontSize = 13.sp,
                                    color = NovaDeepNavy
                                )
                                Spacer(modifier = Modifier.height(4.dp))
                                Text(
                                    text = "সাধারণ সেলুলার কলে থার্ড-পার্টি অডিও সরাসরি ইনজেক্ট করা অ্যান্ড্রয়েড ওএসে সুরক্ষিতভাবে সীমাবদ্ধ। জারভিস কল স্ক্রিপ্ট তৈরি করে স্পিকারে বাজাতে পারে অথবা ডায়ালারে কল প্রস্তুত করতে পারে।",
                                    fontSize = 12.sp,
                                    color = NovaTextPrimary,
                                    lineHeight = 18.sp
                                )
                            }
                        }
                    }
                }
                1 -> {
                    // Autonomous AI Call Dispatcher Tab
                    Column(
                        modifier = Modifier
                            .fillMaxSize()
                            .verticalScroll(rememberScrollState())
                            .padding(16.dp),
                        verticalArrangement = Arrangement.spacedBy(16.dp)
                    ) {
                        Surface(
                            shape = RoundedCornerShape(16.dp),
                            color = Color.White,
                            shadowElevation = 2.dp
                        ) {
                            Column(
                                modifier = Modifier.padding(16.dp),
                                verticalArrangement = Arrangement.spacedBy(12.dp)
                            ) {
                                Text(
                                    text = "স্বয়ংক্রিয় এআই কল মেসেজ প্রস্তুতকরণ",
                                    fontWeight = FontWeight.Bold,
                                    fontSize = 16.sp,
                                    color = NovaTextPrimary
                                )
                                Text(
                                    text = "উদাহরণ: \"জারভিস, রহিমকে কল করে বলো আমি সন্ধ্যা ৬টায় পৌঁছাব\"",
                                    fontSize = 12.sp,
                                    color = NovaTextSecondary
                                )

                                OutlinedTextField(
                                    value = autoRecipientInput,
                                    onValueChange = { autoRecipientInput = it },
                                    label = { Text("প্রাপকের নাম বা নম্বর") },
                                    placeholder = { Text("যেমন: রহিম (Rahim)") },
                                    singleLine = true,
                                    modifier = Modifier.fillMaxWidth(),
                                    shape = RoundedCornerShape(12.dp)
                                )

                                OutlinedTextField(
                                    value = autoMessageInput,
                                    onValueChange = { autoMessageInput = it },
                                    label = { Text("পৌঁছে দেওয়ার বার্তা") },
                                    minLines = 2,
                                    maxLines = 4,
                                    modifier = Modifier.fillMaxWidth(),
                                    shape = RoundedCornerShape(12.dp)
                                )

                                Button(
                                    onClick = {
                                        val recipient = if (autoRecipientInput.isBlank()) "সম্মানিত প্রাপক" else autoRecipientInput
                                        autoGeneratedScript = "হ্যালো $recipient! আমি জারভিস এআই অ্যাসিস্ট্যান্ট, আপনার জন্য একটি জরুরি বার্তা পৌঁছে দিচ্ছি: \"$autoMessageInput\"। ধন্যবাদ!"
                                    },
                                    shape = RoundedCornerShape(12.dp),
                                    colors = ButtonDefaults.buttonColors(containerColor = NovaElectricBlue),
                                    modifier = Modifier.fillMaxWidth().height(46.dp)
                                ) {
                                    Icon(Icons.Default.AutoAwesome, contentDescription = null)
                                    Spacer(modifier = Modifier.width(8.dp))
                                    Text("এআই কল স্ক্রিপ্ট তৈরি করুন")
                                }
                            }
                        }

                        if (autoGeneratedScript.isNotBlank()) {
                            Surface(
                                shape = RoundedCornerShape(16.dp),
                                color = Color.White,
                                shadowElevation = 2.dp
                            ) {
                                Column(
                                    modifier = Modifier.padding(16.dp),
                                    verticalArrangement = Arrangement.spacedBy(12.dp)
                                ) {
                                    Text(
                                        text = "প্রস্তুতকৃত কল বার্তা (AI Disclosure সহ):",
                                        fontWeight = FontWeight.Bold,
                                        fontSize = 14.sp,
                                        color = NovaElectricBlue
                                    )

                                    Text(
                                        text = autoGeneratedScript,
                                        fontSize = 14.sp,
                                        color = NovaTextPrimary,
                                        lineHeight = 22.sp
                                    )

                                    Row(
                                        modifier = Modifier.fillMaxWidth(),
                                        horizontalArrangement = Arrangement.spacedBy(10.dp)
                                    ) {
                                        Button(
                                            onClick = {
                                                viewModel.voiceEngine.speak(
                                                    text = autoGeneratedScript,
                                                    apiKey = viewModel.elevenLabsApiKey.value.ifBlank { null },
                                                    voiceId = viewModel.selectedVoiceId.value,
                                                    speed = viewModel.speechSpeed.value,
                                                    language = "bn"
                                                )
                                            },
                                            shape = RoundedCornerShape(12.dp),
                                            colors = ButtonDefaults.buttonColors(containerColor = NovaSecondaryBlue),
                                            modifier = Modifier.weight(1f)
                                        ) {
                                            Icon(Icons.AutoMirrored.Outlined.VolumeUp, contentDescription = null)
                                            Spacer(modifier = Modifier.width(6.dp))
                                            Text("ভয়েস প্রিভিউ")
                                        }

                                        Button(
                                            onClick = {
                                                viewModel.actionEngine.openDialer(autoRecipientInput)
                                            },
                                            shape = RoundedCornerShape(12.dp),
                                            colors = ButtonDefaults.buttonColors(containerColor = NovaElectricBlue),
                                            modifier = Modifier.weight(1f)
                                        ) {
                                            Icon(Icons.Default.Call, contentDescription = null)
                                            Spacer(modifier = Modifier.width(6.dp))
                                            Text("কল শুরু করুন")
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
                2 -> {
                    // Voice Script Studio Tab
                    Column(
                        modifier = Modifier
                            .fillMaxSize()
                            .padding(16.dp),
                        verticalArrangement = Arrangement.spacedBy(14.dp)
                    ) {
                        Surface(
                            shape = RoundedCornerShape(16.dp),
                            color = Color.White,
                            shadowElevation = 2.dp
                        ) {
                            Column(modifier = Modifier.padding(16.dp)) {
                                Text(
                                    text = "নতুন ভয়েস স্ক্রিপ্ট তৈরি করুন",
                                    fontWeight = FontWeight.Bold,
                                    fontSize = 15.sp,
                                    color = NovaTextPrimary
                                )
                                Spacer(modifier = Modifier.height(10.dp))

                                OutlinedTextField(
                                    value = scriptTitleInput,
                                    onValueChange = { scriptTitleInput = it },
                                    label = { Text("স্ক্রিপ্টের শিরোনাম") },
                                    singleLine = true,
                                    modifier = Modifier.fillMaxWidth(),
                                    shape = RoundedCornerShape(12.dp)
                                )

                                Spacer(modifier = Modifier.height(8.dp))

                                OutlinedTextField(
                                    value = scriptContentInput,
                                    onValueChange = { scriptContentInput = it },
                                    label = { Text("কলের বক্তব্য (যা এআই ভয়েসে পড়া হবে)") },
                                    minLines = 3,
                                    maxLines = 5,
                                    modifier = Modifier.fillMaxWidth(),
                                    shape = RoundedCornerShape(12.dp)
                                )

                                Spacer(modifier = Modifier.height(12.dp))

                                Row(
                                    modifier = Modifier.fillMaxWidth(),
                                    horizontalArrangement = Arrangement.spacedBy(10.dp)
                                ) {
                                    Button(
                                        onClick = {
                                            if (scriptContentInput.isNotBlank()) {
                                                viewModel.voiceEngine.speak(
                                                    text = scriptContentInput,
                                                    apiKey = viewModel.elevenLabsApiKey.value.ifBlank { null },
                                                    voiceId = viewModel.selectedVoiceId.value,
                                                    speed = viewModel.speechSpeed.value,
                                                    language = viewModel.currentLanguage.value
                                                )
                                            }
                                        },
                                        colors = ButtonDefaults.buttonColors(containerColor = NovaSecondaryBlue),
                                        shape = RoundedCornerShape(12.dp),
                                        modifier = Modifier.weight(1f)
                                    ) {
                                        Icon(Icons.Outlined.PlayArrow, contentDescription = null)
                                        Spacer(modifier = Modifier.width(4.dp))
                                        Text("অডিও শুনুন", fontSize = 12.sp)
                                    }

                                    Button(
                                        onClick = {
                                            if (scriptTitleInput.isNotBlank() && scriptContentInput.isNotBlank()) {
                                                viewModel.saveVoiceScript(scriptTitleInput, scriptContentInput)
                                                scriptTitleInput = ""
                                                scriptContentInput = ""
                                                Toast.makeText(context, "স্ক্রিপ্ট সংরক্ষণ করা হয়েছে", Toast.LENGTH_SHORT).show()
                                            }
                                        },
                                        colors = ButtonDefaults.buttonColors(containerColor = NovaElectricBlue),
                                        shape = RoundedCornerShape(12.dp),
                                        modifier = Modifier.weight(1f)
                                    ) {
                                        Icon(Icons.Default.Save, contentDescription = null)
                                        Spacer(modifier = Modifier.width(4.dp))
                                        Text("সংরক্ষণ", fontSize = 12.sp)
                                    }
                                }
                            }
                        }

                        Text(
                            text = "সংরক্ষিত স্ক্রিপ্টসমূহ (${voiceScripts.size})",
                            fontWeight = FontWeight.Bold,
                            fontSize = 15.sp,
                            color = NovaTextPrimary
                        )

                        LazyColumn(
                            modifier = Modifier.fillMaxWidth().weight(1f),
                            verticalArrangement = Arrangement.spacedBy(8.dp)
                        ) {
                            items(voiceScripts, key = { it.id }) { script ->
                                Surface(
                                    shape = RoundedCornerShape(12.dp),
                                    color = Color.White,
                                    border = BorderStroke(1.dp, NovaBorderLight)
                                ) {
                                    Row(
                                        modifier = Modifier.padding(14.dp),
                                        verticalAlignment = Alignment.CenterVertically,
                                        horizontalArrangement = Arrangement.SpaceBetween
                                    ) {
                                        Column(modifier = Modifier.weight(1f)) {
                                            Text(script.title, fontWeight = FontWeight.Bold, fontSize = 14.sp)
                                            Text(script.content, fontSize = 12.sp, color = NovaTextSecondary, maxLines = 2)
                                            Text("ভয়েস: ${script.voiceName}", fontSize = 10.sp, color = NovaTextMuted)
                                        }

                                        Row {
                                            IconButton(onClick = {
                                                viewModel.voiceEngine.speak(
                                                    text = script.content,
                                                    apiKey = viewModel.elevenLabsApiKey.value.ifBlank { null },
                                                    voiceId = script.voiceId,
                                                    speed = viewModel.speechSpeed.value,
                                                    language = viewModel.currentLanguage.value
                                                )
                                            }) {
                                                Icon(Icons.Outlined.PlayArrow, contentDescription = "Play", tint = NovaElectricBlue)
                                            }

                                            IconButton(onClick = { viewModel.deleteVoiceScript(script.id) }) {
                                                Icon(Icons.Outlined.Delete, contentDescription = "Delete", tint = NovaErrorRed)
                                            }
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}
